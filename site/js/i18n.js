function fmtNum(n, digits, lang) {
  if (n == null) return "–";
  return Number(n).toLocaleString(lang === "fr" ? "fr-CA" : "en-CA", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}
